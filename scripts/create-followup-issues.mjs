import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";

const proposal = JSON.parse(await readFile("proposal.json", "utf8"));

if (proposal.type !== "followup_issues" || !Array.isArray(proposal.issues)) {
  throw new Error("proposal.json does not contain follow-up issues");
}
if (!process.env.GH_TOKEN) {
  throw new Error("LAB_DEPLOY_TOKEN is required to create follow-up issues");
}

for (const followup of proposal.issues) {
  const provenance = `\n\n---\nGenerated by Maintainer Assistant as a follow-up to #${proposal.source_issue}.`;
  const url = execFileSync("gh", [
    "issue",
    "create",
    "--title",
    followup.title,
    "--body",
    `${followup.body}${provenance}`,
  ], {
    encoding: "utf8",
    env: process.env,
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();
  console.log(`Created ${url}`);
}
